"""One government's answers to every question: state law steps, the local layer, contacts, sources.

:func:`answers_for` is what the dashboard's place page and the browser plugin's lookup show;
:func:`markdown` renders the same thing as a document (``lexflow answer va:charlottesville``).
"""
from __future__ import annotations

from ..store import db
from . import stats
from .questions import QUESTIONS


def answers_for(con, gov_id: str) -> dict | None:
    g = db.one(con, "SELECT * FROM governments WHERE gov_id=?", gov_id)
    if not g:
        return None
    out = {"government": g, "answers": {}}
    for a in db.rows(con, "SELECT * FROM answers WHERE gov_id=?", gov_id):
        a["summary"] = db.loads(a["summary"], {})
        m = stats.model_detail(con, a["model_id"]) if a["model_id"] else None
        a["steps"] = stats.steps_of(m)
        a["law"] = db.one(con, "SELECT citation, heading, url, method, score FROM located_law "
                               "WHERE state=? AND question=?", a["state"], a["question"])
        a["model"] = {k: m[k] for k in ("model_id", "title", "tier", "built_by", "quality", "completion")} if m else None
        loc = db.one(con, "SELECT * FROM local_answers WHERE gov_id=? AND question=?", gov_id, a["question"])
        if loc:
            for k in ("steps", "contacts", "local_law", "caveats", "sources"):
                loc[k] = db.loads(loc[k], [])
        a["local"] = loc
        a["locus"] = db.rows(con, "SELECT header, function, topic, score FROM local_law WHERE gov_id=? AND "
                                  "question=? AND score > 0 ORDER BY score DESC LIMIT 8", gov_id, a["question"])
        a["decisions"] = ((m or {}).get("facts") or {}).get("decisions", [])
        a["gaps"] = ((m or {}).get("metrics") or {}).get("gaps", [])
        out["answers"][a["question"]] = a
    out["contacts"] = db.rows(con, "SELECT question, kind, value, label, source FROM contacts WHERE gov_id=?", gov_id)
    return out


def _cell(x) -> str:
    return str(x).strip().strip('"').replace("|", "/")


def _table(d: dict) -> list[str]:
    head = [c["label"] for c in d["inputs"]] + [f"→ {c['label']}" for c in d["outputs"]]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in d["rules"]:
        lines.append("| " + " | ".join(_cell(x) for x in r["when"] + r["then"]) + " |")
    return lines


def markdown(con, gov_id: str) -> str:
    d = answers_for(con, gov_id)
    if d is None:
        raise KeyError(gov_id)
    g = d["government"]
    L = [f"# {g['name']}", "",
         f"_{g['kind'].title()}, {g['state'].upper()}"
         + (f", population {g['population']:,}" if g.get("population") else "") + "._ "
         "Generated by lexflow from the state statutes (open-us-law), Claude-checked process models and "
         "researched local sources. This is information, not legal advice.", ""]
    for qid, q in QUESTIONS.items():
        a = d["answers"].get(qid)
        L += [f"## {q.title.rstrip('?')} in {g['name']}?", ""]
        if not a:
            L += ["Not scored yet.", ""]
            continue
        loc = a.get("local") or {}
        law = a.get("law") or {}
        tier = {"reviewed": "checked by Claude", "agreed": "two independent extractions agree", "single": "one extraction (unreviewed)",
                "found": "law located, steps not modelled", "none": "no state law found"}.get(a["tier"], a["tier"])
        L += [f"**Confidence {a['confidence']:.2f}** (state law {a['state_score']:.2f}, local {a['local_score']:.2f}, "
              f"contact {a['contact_score']:.2f}; state model {tier}).", ""]
        if loc.get("summary"):
            L += [loc["summary"], ""]
        if a.get("steps"):
            L += [f"### What state law requires" + (f" ({law['citation']})" if law.get("citation") else ""), ""]
            for i, s in enumerate(a["steps"], 1):
                dl = f", within {s['deadline']}" if s.get("deadline") else ""
                duty = f" ({s['modality']})" if s.get("modality") and s["modality"] != "none" else ""
                L.append(f"{i}. **{s['step']}** - {s['who']}{dl}{duty}. {s['cite']}")
                if s.get("quote"):
                    L.append(f"   > {s['quote']}")
            L.append("")
        for t in a.get("decisions") or []:
            if qid == "business" and t["id"] != "business_structure":
                continue
            L += [f"### {t['question']}", ""] + _table(t) + [""]
        if loc.get("steps"):
            L += [f"### What {g['name']} adds", ""]
            for i, s in enumerate(loc["steps"], 1):
                L.append(f"{i}. **{s['step']}**" + (f" - {s['who']}" if s.get("who") else "") + f". {s.get('how', '')}"
                         + (f" ([source]({s['url']}))" if s.get("url") else ""))
            L.append("")
        contacts = loc.get("contacts") or []
        if contacts:
            L += ["### Who to contact", ""]
            for c in contacts:
                v = c.get("value") or c.get("url")
                link = f"[{c.get('label') or v}]({v})" if str(v).startswith("http") else f"{c.get('label', '')}: {v}"
                L.append(f"- {link}")
            L.append("")
        if loc.get("local_law"):
            L += ["### Local law", ""] + [f"- [{x['citation']}]({x['url']}): {x['summary']}" if x.get("url")
                                          else f"- {x['citation']}: {x['summary']}" for x in loc["local_law"]] + [""]
        if loc.get("fees"):
            L += [f"**Fees.** {loc['fees']}", ""]
        cases = (stats.model_detail(con, a["model_id"]) or {}).get("cases") if a.get("model_id") else None
        if cases:
            L += ["### Court decisions citing this law", ""]
            for c in cases[:8]:
                cite = f", {c['citation']}" if c.get("citation") else ""
                L.append(f"- [{c['case_name']}]({c['url']}) ({c.get('court') or ''}, {(c.get('date_filed') or '')[:4]}{cite})")
            L.append("")
        caveats = (loc.get("caveats") or []) + (a.get("gaps") or [])
        if caveats:
            L += ["### Caveats and gaps", ""] + [f"- {c}" for c in caveats] + [""]
    sources = []
    for a in d["answers"].values():
        for s in ((a.get("local") or {}).get("sources") or []):
            if s.get("url") and s["url"] not in [x["url"] for x in sources]:
                sources.append(s)
    if sources:
        L += ["## Sources", ""] + [f"- [{s.get('title') or s['url']}]({s['url']})" for s in sources] + [""]
    return "\n".join(L).rstrip() + "\n"

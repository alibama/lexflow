def human_duration(iso: str) -> str:
    m = re.fullmatch(r"P(?:(\d+)Y)?(?:(\d+)M)?(?:(\d+)W)?(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?)?", iso or "")
    if not m:
        return iso
    names = ["year", "month", "week", "day", "hour", "minute"]
    parts = [f"{int(v)} {n}{'s' if int(v) != 1 else ''}" for v, n in zip(m.groups(), names) if v]
    return ", ".join(parts) or iso


def model_data(key, m):
    actors = {a.id: a.name for a in m.actors}
    lane_actor = {lane.id: lane.actor for p in m.processes() for lane in p.lanes}
    part_actor = {p.process.id: p.actor for p in m.participants if p.process}
    elements = {}
    parent = {n.id: scope.id for _, scope, n in m.iter_nodes() if scope is not None}
    by_id = {n.id: n for _, _, n in m.iter_nodes()}

    def lane_of(node):
        cur = node
        while cur is not None:
            if cur.lane:
                return cur.lane
            if cur.type == "boundaryEvent" and cur.attached_to:
                cur = by_id.get(cur.attached_to)
                continue
            cur = by_id.get(parent.get(cur.id, ""))
        return None

    for proc, scope, n in m.iter_nodes():
        actor = n.bearer or lane_actor.get(lane_of(n) or "") or part_actor.get(proc.id)
        kind = TYPE_LABEL.get(n.type, n.type)
        if n.event == "timer":
            kind = "Deadline (boundary timer)" if n.type == "boundaryEvent" else "Deadline (timer)"
        elif n.event == "message" and n.type != "boundaryEvent":
            kind = "Message received" if "Catch" in n.type or n.type == "startEvent" else kind
        elif n.type == "boundaryEvent" and n.event == "message":
            kind = "Message that can arrive during the step"
        if n.triggered_by_event:
            kind = "Event sub-process (can happen at any time)"
        groundings = [s.grounding for s in n.sources]
        g = "explicit" if "explicit" in groundings else ("implied" if "implied" in groundings else
                                                         ("assumed" if groundings else None))
        elements[n.id] = {
            "name": n.name or "", "type": n.type, "kind": kind, "actor": actors.get(actor, ""), "grounding": g,
            "deontic": n.deontic, "bearer": actors.get(n.bearer or "", ""),
            "timer": ({"value": n.timer.value, "human": human_duration(n.timer.value), "anchor": n.timer.anchor,
                       "strict": n.timer.strict, "interrupting": n.interrupting} if n.timer else None),
            "decision": n.decision_ref, "calls": n.called_element, "doc": n.documentation,
            "sources": [{"citation": s.citation, "key": f"{s.code}|{s.section}", "quote": s.quote,
                         "grounding": s.grounding, "note": s.note, "url": s.url} for s in n.sources],
        }
    texts = [{"key": f"{t.code}|{t.section}", "section": t.section, "code": t.code, "title": t.title,
              "text": t.text, "url": t.url, "history": t.history, "retrieved": t.retrieved_from}
             for t in m.texts]
    decisions = [{"id": d.id, "name": d.name, "question": d.question, "hit": d.hit_policy,
                  "inputs": [i.label for i in d.inputs], "outputs": [o.label for o in d.outputs],
                  "rules": [{"id": r.id, "in": r.inputs, "out": r.outputs,
                             "cite": "; ".join(s.citation for s in r.sources) or (r.annotation or "")}
                            for r in d.rules]} for d in m.decisions]
    rep = REPORT["models"][key]
    petri = {pid: {k: v for k, v in val.items() if k in ("places", "transitions", "sound", "reachable_states",
                                                          "powl", "approximations")}
             for pid, val in rep["petri"].items()}
    proc_names = {p.id: p.name for p in m.processes()}
    checks = {
        "bpmn_xsd": len(rep["bpmn_xsd_errors"]), "dmn_xsd": len(rep.get("dmn_xsd_errors") or []),
        "lint": len(rep["bpmnlint"]), "dmnlint": rep.get("dmnlint_ok"), "layout": len(rep["layout_warnings"]),
        "quotes": rep["lex"]["quotes_checked"], "quote_misses": rep["lex"]["quote_misses"],
        "grounding": rep["lex"]["grounding"], "explicit_share": rep["lex"]["explicit_share"],
        "counts": rep["counts"], "wikibase": rep["wikibase"], "scenarios": SCENARIOS.get(key, []),
    }
    return {"id": key, "label": LABEL[key], "title": m.title, "jurisdiction": m.jurisdiction_name,
            "qid": m.jurisdiction_qid, "summary": m.summary, "note": NOTE[key],
            "xml": (OUT / f"{key}.bpmn").read_text(), "elements": elements, "texts": texts,
            "decisions": decisions, "petri": petri, "procNames": proc_names, "gaps": m.review.gaps,
            "status": m.review.status, "method": m.provenance.method, "checks": checks,
            "default": DEFAULT_SELECT[key]}


def legistar_data():
    d = json.loads((ROOT / "fixtures/legistar/albemarle_2026.json").read_text())
    cases = build_cases(d["matters"], d["histories"])
    c = conformance(cases)
    rows = []
    for case in cases:
        ev = sorted(case.events, key=lambda e: e["time"])
        days = None
        if len(ev) >= 2:
            from datetime import date
            days = (date.fromisoformat(ev[-1]["time"]) - date.fromisoformat(ev[0]["time"])).days
        rows.append({"case": case.case_id, "subject": subject(case.title), "title": case.title,
                     "matters": case.matters, "trace": case.trace, "dates": [e["time"] for e in ev], "days": days})
    return {"cases": rows, "findings": c.findings, "unobservable": c.unobservable_steps,
            "variants": c.variants, "source": d["source"]}


def build():
    models = {name: fn() for name, fn in gold.ALL.items() if name != "va_judicial_review_stub"}
    facts = LegalProcessFacts.model_validate_json((ROOT / "fixtures/gold/albemarle_17_211.facts.json").read_text())
    g = models["albemarle_17_211"]
    models["compiled_17_211"] = compile_facts(
        facts, model_id="va-albemarle-17-211-compiled", jurisdiction=g.jurisdiction,
        jurisdiction_name=g.jurisdiction_name, code="Albemarle County Code", text=g.texts[0],
        jurisdiction_qid=g.jurisdiction_qid)
    rows = json.loads((ROOT / "fixtures/locus/va_samples.json").read_text())["rows"]
    flags = {}
    for key, val, code, juris in [("county", "albemarle_county", "Albemarle County Code", "va/albemarle_county"),
                                  ("city", "charlottesville", "Charlottesville City Code", "va/charlottesville")]:
        for s in resegment([r for r in rows if r[key] == val], code, juris):
            if s.flags:
                flags[f"{code} § {s.number}"] = s.flags
    data = {"models": [model_data(k, models[k]) for k in ("albemarle_17_211", "charlottesville_noise", "compiled_17_211")],
            "legistar": legistar_data(), "locusFlags": flags,
            "built": "2026-10-06"}
    css_bpmn = (ROOT / "tools" / "bpmn-js-18.31.0.min.css").read_text()
    template = (ROOT / "scripts" / "viewer_template.html").read_text()
    page = template.replace("/*__BPMN_CSS__*/", css_bpmn).replace(
        "__DATA__", json.dumps(data, ensure_ascii=False).replace("</", "<\\/"))
    out = OUT / "viewer"
    out.mkdir(parents=True, exist_ok=True)
    (out / "lexipedia-viewer.html").write_text(page)
    script = re.search(r"<script>\n(.*?)</script>\s*$", page, re.S)
    (out / "_app.js").write_text(script.group(1) if script else "")
    print("wrote", out / "lexipedia-viewer.html", f"{len(page) / 1024:.0f} KB")


if __name__ == "__main__":
    build()
